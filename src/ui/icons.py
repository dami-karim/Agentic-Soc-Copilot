    path = _PATHS.get(name)
    if path is None:
        return ""
    aria = f' role="img" aria-label="{_html.escape(label)}"' if label else \
        ' aria-hidden="true"'
    klass = f' class="{_html.escape(cls)}"' if cls else ""
    return (
        f'<svg viewBox="0 0 24 24" width="{size}" height="{size}" '
        f'fill="none" stroke="currentColor" stroke-width="{stroke}" '
        f'stroke-linecap="round" stroke-linejoin="round"{klass}{aria}>'
        f'{path}</svg>'
    )


